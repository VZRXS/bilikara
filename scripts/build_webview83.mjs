// Reproducible compatibility artifacts from the same UI. No source/vendor edits.
import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { transform as javascript } from 'esbuild';
import { transform as stylesheet } from 'lightningcss';
const defaultRoot = fileURLToPath(new URL('../static/', import.meta.url));
// Chromium's prefixed :any handles simple alternatives. Complex alternatives
// need expansion; fail closed if a future selector would change the subject.
function expandComplexIs(selector) {
  const index = selector.findIndex(part => part.kind === 'is' && part.selectors.some(branch => branch.some(part => part.type === 'combinator')));
  if (index < 0) return [selector];
  if (index > 0 && selector[index - 1].type !== 'combinator') throw new Error('Unsupported compound complex :is selector; review its subject');
  return selector[index].selectors.flatMap(branch => expandComplexIs([...selector.slice(0, index), ...branch, ...selector.slice(index + 1)]));
}
export async function artifacts(root = defaultRoot) {
  const outputs = new Map();
  const styles = new Set(['index.html', 'controller.html'].flatMap(name =>
    Array.from(readFileSync(path.join(root, name), 'utf8').matchAll(/<link[^>]+href="\/([^"/]+\.css)"/g), match => match[1])));
  for (const name of styles) {
    let source = readFileSync(path.join(root, name), 'utf8').replace(/\r\n|\r/g, '\n');
    // These are the finite relation adapters already maintained by the shared UI.
    // :has/:where cannot be polyfilled by a parser. Select only the legacy branch.
    source = source.replace(/:is\(:has\((.*?)\), :where\((\[data-legacy-has[^\]]+\])\)\)/gs, '$2')
      .replace('html[data-host-layout="portrait"] :where(.android-host-only):not([hidden])',
        'html[data-host-layout="portrait"] .android-host-only').replace(/:focus-visible/g, ':focus')
      .replace(/(?<![\w-])overflow:\s*clip/g, 'overflow: hidden')
      .replace(/aspect-ratio:\s*([^;{}]+)/g, '$&; --legacy-aspect-ratio: $1')
      .replace(/url\((['"]?)([^)'"\s]+)\1\)/g, (all, quote, url) => /^(?:[a-z]+:|\/|#)/i.test(url) ? all : `url("/${url.replace(/^\.\//, '')}")`);
    if (source.includes(':where(')) throw new Error('Unmapped zero-specificity selector: ' + name);
    // Replacing :where(.android-host-only):not([hidden]) with the class retains
    // its specificity. Keep the hidden branch explicit so later grid/flex rules
    // still override the ordinary display:block without exposing hidden rows.
    if (name === 'host-layout.css') source += '\nhtml[data-host-layout="portrait"] .android-host-only[hidden]{display:none}\n';
    const result = stylesheet({ filename: name, code: Buffer.from(source), targets: {chrome: 83 << 16}, minify: false, visitor: {Selector: expandComplexIs} });
    const sha = createHash('sha256').update(readFileSync(path.join(root, name), 'utf8').replace(/\r\n|\r/g, '\n')).digest('hex');
    outputs.set('compat83/' + name, `/* Generated by npm run prepare:webview83; ${name} SHA256 ${sha}. */\n` + result.code.toString());
  }
  const vendor = readFileSync(path.join(root, 'vendor/signalsmith-stretch/SignalsmithStretch.js'), 'utf8').replace(/\r\n|\r/g, '\n');
  const compiled = await javascript(vendor, {target: 'chrome83', format: 'esm', legalComments: 'inline', charset: 'utf8'});
  const output = '// Generated from the pinned SignalsmithStretch.js by npm run prepare:webview83. MIT; see README.md.\n' + compiled.code;
  const wasm = text => text.match(/data:application\/octet-stream;base64,([^"']+)/)[1];
  if (wasm(vendor) !== wasm(output)) throw new Error('Embedded DSP bytes changed');
  outputs.set('vendor/signalsmith-stretch/SignalsmithStretch83.js', output);
  return outputs;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.slice(2).includes('--check');
  for (const [name, output] of await artifacts()) {
    const target = path.join(defaultRoot, name);
    if (check) {
      if (readFileSync(target, 'utf8').replace(/\r\n|\r/g, '\n') !== output) throw new Error('Stale WebView 83 artifact: ' + name);
    } else { mkdirSync(path.dirname(target), {recursive: true}); writeFileSync(target, output, 'utf8'); }
  }
}
