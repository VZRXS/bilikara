import assert from 'node:assert/strict';
import test, {before} from 'node:test';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {chromium,webkit} from 'playwright';
import {root} from './desktop_construction_support.mjs';
import {buildNativeHost} from './native_runtime_artifacts.mjs';
import {RunningHost,isolatedEnvironment} from './native_host_support.mjs';
import {writeR7Seed} from './queue_r7_support.mjs';
let executable;
before(async()=>{executable=process.env.BILIKARA_TEST_NATIVE_HOST_BINARY||await buildNativeHost();},{timeout:300000});
for(const engine of [chromium,webkit])test(engine.name()+' R7 Host/Remote preserve queue order and refresh rejected snapshots',{timeout:150000},async t=>{
  const home=mkdtempSync(path.join(tmpdir(),'bilikara-r7-browser-'));writeR7Seed(home);
  let browser,host;
  t.after(async()=>{await browser?.close();await host?.close();rmSync(home,{recursive:true,force:true});});
  host=await RunningHost.start(executable,home,['--headless','--port','0','--data-dir',path.join(home,'data'),'--static-dir',path.join(root,'static')],isolatedEnvironment(home));
  await host.api('/api/session/startup-choice',{choice:'continue'});
  browser=await engine.launch();
  const context=await browser.newContext({viewport:{width:700,height:900},hasTouch:true});
  await context.addCookies([...host.cookies].map(([name,value])=>({name,value,url:host.base})));
  await context.addInitScript(()=>{localStorage.setItem('bilikara.update.automatic','false');localStorage.setItem('bilikara.ui.playback-restart-seen.host.v1','true');localStorage.setItem('bilikara.ui.playback-restart-seen.remote.v1','true');});
  await context.route('**/*',route=>new URL(route.request().url()).origin===host.base?route.continue():route.abort());
  const page=await context.newPage();
  await page.goto(host.base+'/');
  await page.waitForFunction(()=>typeof state!=='undefined'&&state.data?.queue_version);
  const initial=await host.api('/api/state');
  const sent=[];page.on('request',r=>{if(r.url().endsWith('/api/playlist/move-next'))sent.push(r.postDataJSON());});
  await page.evaluate(async()=>acceptHostStateSnapshot(await apiPost('/api/playlist/move-next',{item_id:'C1'})));
  assert.equal(sent[0].expected_queue_version,initial.queue_version);
  await page.evaluate(async()=>{delete state.data.queue_mutation_version;acceptHostStateSnapshot(await apiPost('/api/playlist/move-next',{item_id:'C1'}));});
  assert.equal(sent[1].expected_queue_version,undefined,'old Host capability omits the additive field');
  assert.deepEqual((await host.api('/api/state')).playlist.map(i=>i.id),['C1','B1','A1','B2','C2','A2']);
  const observed=await page.evaluate(()=>state.data.queue_version);
  await host.api('/api/playlist/move-next',{item_id:'B2',expected_queue_version:observed});
  // Explicit original token represents a gesture/menu confirmed before the competing move.
  const rejected=await page.evaluate(async version=>{try{await apiPost('/api/playlist/move-next',{item_id:'A2',expected_queue_version:version});return null;}catch(e){return {code:e.code,version:state.data.queue_version};}},observed);
  assert.equal(rejected.code,'queue_changed');assert.equal(rejected.version,(await host.api('/api/state')).queue_version);
  const remoteContext=await browser.newContext({viewport:{width:393,height:844},hasTouch:true});
  await remoteContext.route('**/*',route=>new URL(route.request().url()).origin===host.base?route.continue():route.abort());
  const remote=await remoteContext.newPage();await remote.goto(host.base+'/remote');
  await remote.waitForFunction(()=>typeof state!=='undefined'&&state.data&&!state.remoteIdentityChecking);
  await remote.evaluate(async()=>applyRemoteIdentity(await apiPost('/api/remote-identity/register',{name:'A',claim:true})));
  const remoteSent=[];remote.on('request',r=>{if(r.url().endsWith('/api/playlist/move-next'))remoteSent.push(r.postDataJSON());});
  await remote.evaluate(async()=>applyStateSnapshot(await apiPost('/api/playlist/move-next',{item_id:'C2'})));
  assert.equal(typeof remoteSent[0].expected_queue_version,'string');
  const after=await host.api('/api/state');assert.deepEqual(after.playlist.map(i=>i.id),['C2','B2','C1','B1','A1','A2']);
  await remote.reload();await remote.waitForFunction(()=>typeof state!=='undefined'&&state.data?.playlist?.[0]?.id==='C2');
  assert.deepEqual((await host.api('/api/state')).playlist.map(i=>i.id),after.playlist.map(i=>i.id));
  // A nonblocking Host confirmation must retain the version shown when opened.
  await page.bringToFront();
  await page.evaluate(async()=>{const reply=await(await fetch('/api/state')).json();acceptHostStateSnapshot(reply.data);activateHostWorkspace('queue');render();});
  await page.waitForFunction(version=>state.renderedQueue?.version===version,after.queue_version);
  await page.waitForFunction(()=>elements.playlist.querySelector('button[data-action="remove"][data-id="A2"]'));
  await page.evaluate(()=>elements.playlist.querySelector('button[data-action="remove"][data-id="A2"]').click());
  const confirmedVersion=await page.evaluate(()=>state.confirmIntent.queueVersion);
  assert.equal(confirmedVersion,after.queue_version);
  const concurrent=await host.api('/api/playlist/move-next',{item_id:'B1',expected_queue_version:confirmedVersion});
  await page.evaluate(async()=>{const reply=await(await fetch('/api/state')).json();acceptHostStateSnapshot(reply.data);render();});
  assert.equal(await page.evaluate(()=>state.data.queue_version),concurrent.queue_version);
  assert.equal(await page.evaluate(()=>state.confirmIntent.queueVersion),confirmedVersion);
  const response=page.waitForResponse(r=>r.url().endsWith('/api/playlist/remove'));
  await page.evaluate(()=>elements.confirmOk.click());
  assert.equal((await response).status(),409);
  assert.deepEqual((await host.api('/api/state')).playlist.map(i=>i.id),concurrent.playlist.map(i=>i.id));

});
