//! Opt-in staging of an existing ShowHost DLL; no application imports, Show
//! builds, DLL execution, downloads or dependency collection from PATH.
use crate::{
    Result,
    config::{Config, Os},
    files::{self, Layout},
    libav,
};
use object::{Object, ObjectKind, read::pe::PeFile64};
use serde_json::json;
use sha2::{Digest, Sha256};
use std::{
    collections::HashSet,
    fs,
    path::{Path, PathBuf},
};

const REQUIRED_SYMBOLS: &[&str] = &[
    "show_host_create",
    "show_host_destroy",
    "show_host_load_with_options",
    "show_host_prepare_next",
    "show_host_set_audience_hud_state",
    "show_host_start_cast_stream",
    "show_host_get_cast_stream_port",
    "show_host_stop_cast_stream",
    "show_host_play",
    "show_host_pause",
    "show_host_stop",
    "show_host_seek",
    "show_host_set_volume",
    "show_host_set_key_semitones",
    "show_host_set_audio_clock_offset",
    "show_host_get_state",
    "show_host_get_position",
    "show_host_get_duration",
    "show_host_is_buffering",
    "show_host_get_cast_pipeline_stats",
];
const DLL: &str = "libshow_host.dll";
// Generated by the same Show build as the DLL; includes the HUD's third-party
// components as well as the engine and audio-processing licenses.
const LICENSES: &[&str] = &["libshow_host.dll.LICENSES.txt"];

fn system_import(name: &str) -> bool {
    let name = name.to_ascii_lowercase();
    (name.starts_with("api-ms-win-crt-") && name.ends_with(".dll"))
        || matches!(
            name.as_str(),
            "advapi32.dll"
                | "d2d1.dll"
                | "d3d11.dll"
                | "dcomp.dll"
                | "dsound.dll"
                | "dwrite.dll"
                | "gdi32.dll"
                | "iphlpapi.dll"
                | "kernel32.dll"
                | "mf.dll"
                | "mfplat.dll"
                | "mfreadwrite.dll"
                | "ole32.dll"
                | "oleaut32.dll"
                | "shlwapi.dll"
                | "user32.dll"
                | "ws2_32.dll"
        )
}

/// Canonicalize existing ancestors before adding a not-yet-created output path.
fn resolved_output(path: &Path) -> Result<PathBuf> {
    if path.exists() || path.is_symlink() {
        return Ok(path.canonicalize()?);
    }
    let parent = path
        .parent()
        .ok_or("ShowHost output has no existing ancestor")?;
    let name = path.file_name().ok_or("Invalid ShowHost output name")?;
    Ok(resolved_output(parent)?.join(name))
}

fn independent_paths(source: &Path, layout: &Layout) -> Result<()> {
    for destination in [
        layout.vendor.join("show-host"),
        layout.docs.join("THIRD_PARTY_LICENSES/kirakara-show"),
    ] {
        let destination = resolved_output(&destination)?;
        if source.starts_with(&destination) || destination.starts_with(source) {
            return Err(
                "ShowHost input and generated vendor/license outputs must be separate directories"
                    .into(),
            );
        }
    }
    Ok(())
}

fn owned_outputs(anchor: &Path, root: &Path, paths: &[&str]) -> Result<()> {
    if root.is_symlink() {
        return Err("Refusing a linked generated ShowHost directory".into());
    }
    let resolved_root = resolved_output(root)?;
    if !resolved_root.starts_with(resolved_output(anchor)?) {
        return Err("Generated ShowHost directory escaped its layout".into());
    }
    for name in paths {
        let path = root.join(name);
        if path.is_symlink() || !resolved_output(&path)?.starts_with(&resolved_root) {
            return Err("Generated ShowHost output escaped its owned directory".into());
        }
    }
    Ok(())
}

fn source_file(root: &Path, relative: &str) -> Result<PathBuf> {
    let path = root.join(relative);
    if !fs::symlink_metadata(&path)
        .is_ok_and(|metadata| metadata.is_file() && !metadata.is_symlink())
    {
        return Err(format!(
            "ShowHost requires a regular, unlinked input file: {}",
            path.display()
        )
        .into());
    }
    let resolved = path.canonicalize()?;
    if !resolved.starts_with(root) {
        return Err("ShowHost input escaped its prepared directory".into());
    }
    if fs::metadata(&resolved)?.len() == 0 {
        return Err(format!("ShowHost input is empty: {}", path.display()).into());
    }
    Ok(resolved)
}

fn atomic_copy(source: &Path, destination: &Path) -> Result<()> {
    let parent = destination
        .parent()
        .ok_or("Invalid ShowHost output parent")?;
    fs::create_dir_all(parent)?;
    let temporary = tempfile::NamedTempFile::new_in(parent)?;
    files::copy(source, temporary.path())?;
    temporary.persist(destination)?;
    Ok(())
}

fn remove_owned_file(path: &Path) -> Result<()> {
    if path.is_symlink() {
        return Err(format!(
            "Refusing a linked generated ShowHost output: {}",
            path.display()
        )
        .into());
    }
    if path.exists() {
        if !path.is_file() {
            return Err(format!(
                "Generated ShowHost output is not a file: {}",
                path.display()
            )
            .into());
        }
        fs::remove_file(path)?;
    }
    Ok(())
}

/// Called by both adjacent development preparation and release assembly.
/// All source, architecture, ABI and dependency checks precede publication.
pub fn stage(config: &Config, layout: &Layout) -> Result<()> {
    let directory = config.env.get("BILIKARA_SHOW_HOST_DIR");
    let vendor = layout.vendor.join("show-host");
    let licenses = layout.docs.join("THIRD_PARTY_LICENSES/kirakara-show");
    owned_outputs(&layout.vendor, &vendor, &[DLL, "show-host.json"])?;
    owned_outputs(&layout.docs, &licenses, LICENSES)?;
    let Some(directory) = directory else {
        // Reusing a generated output must not retain a prior opt-in DLL.
        for name in [DLL, "show-host.json"] {
            remove_owned_file(&vendor.join(name))?;
        }
        for name in LICENSES {
            remove_owned_file(&licenses.join(name))?;
        }
        return Ok(());
    };
    if config.platform.os != Os::Windows || config.platform.arm || layout.macos_app {
        return Err("BILIKARA_SHOW_HOST_DIR supports only native Windows x64 builds".into());
    }
    let directory = Path::new(directory);
    if !directory.is_absolute() || !directory.is_dir() {
        return Err("BILIKARA_SHOW_HOST_DIR must be an absolute prepared directory".into());
    }
    let directory = directory.canonicalize()?;
    independent_paths(&directory, layout)?;
    let dll = source_file(&directory, DLL)?;
    let license_inputs: Vec<_> = LICENSES
        .iter()
        .map(|name| source_file(&directory, name))
        .collect::<Result<_>>()?;
    let bytes = fs::read(&dll)?;
    let pe = PeFile64::parse(bytes.as_slice())?;
    if pe.kind() != ObjectKind::Dynamic {
        return Err("ShowHost input must be a Windows x64 PE DLL".into());
    }
    let exports = pe.exports()?;
    let exported: HashSet<_> = exports.iter().map(|symbol| symbol.name()).collect();
    for symbol in REQUIRED_SYMBOLS {
        if !exported.contains(symbol.as_bytes()) {
            return Err(format!(
                "ShowHost missing symbol: {symbol}; expected ShowHost Cast with audience HUD ABI v1"
            )
            .into());
        }
    }
    // Includes delay imports and rejects a foreign machine without loading it.
    let mut imports = libav::binary_imports(&dll, config.platform)?;
    imports.sort();
    imports.dedup();
    if let Some(import) = imports.iter().find(|name| !system_import(name)) {
        return Err(format!("ShowHost has an undeclared private/runtime DLL dependency: {import}; prepare a supported self-contained DLL, dependencies are never copied from PATH").into());
    }
    atomic_copy(&dll, &vendor.join(DLL))?;
    for (name, input) in LICENSES.iter().zip(license_inputs) {
        atomic_copy(&input, &licenses.join(name))?;
    }
    files::write_json(
        &vendor.join("show-host.json"),
        &json!({
            "schema_version": 1, "file": DLL, "target": config.platform.target(),
            "sha256": format!("{:x}", Sha256::digest(&bytes)),
            "required_symbols": REQUIRED_SYMBOLS, "system_imports": imports,
        }),
    )?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::config::{Environment, Platform};

    fn configuration(root: &Path, input: Option<&Path>, os: &str, arch: &str) -> Config {
        let mut environment = Environment::default();
        if let Some(input) = input {
            environment.0.insert(
                "BILIKARA_SHOW_HOST_DIR".into(),
                input.as_os_str().to_owned(),
            );
        }
        Config::new(root, Platform::new(os, arch).unwrap(), environment, None).unwrap()
    }

    // Static PE64 fixture, never executable Windows acceptance evidence.
    fn pe(symbols: &[&str], import: &str) -> Vec<u8> {
        let mut bytes = vec![0_u8; 0x1400];
        bytes[..2].copy_from_slice(b"MZ");
        bytes[0x3c..0x40].copy_from_slice(&0x80_u32.to_le_bytes());
        bytes[0x80..0x84].copy_from_slice(b"PE\0\0");
        bytes[0x84..0x86].copy_from_slice(&0x8664_u16.to_le_bytes());
        bytes[0x86..0x88].copy_from_slice(&1_u16.to_le_bytes());
        bytes[0x94..0x96].copy_from_slice(&0xf0_u16.to_le_bytes());
        bytes[0x96..0x98].copy_from_slice(&0x2002_u16.to_le_bytes());
        bytes[0x98..0x9a].copy_from_slice(&0x20b_u16.to_le_bytes());
        for (offset, value) in [
            (0x104, 16_u32),
            (0x108, 0x1000),
            (0x10c, 0xe00),
            (0x110, 0x1e00),
            (0x114, 40),
            (0x190, 0x1200),
            (0x194, 0x1000),
            (0x198, 0x1200),
            (0x19c, 0x200),
            (0x20c, 0x1090),
            (0x210, 1),
            (0x214, symbols.len() as u32),
            (0x218, symbols.len() as u32),
            (0x21c, 0x1100),
            (0x220, 0x1200),
            (0x224, 0x1300),
            (0x100c, 0x1e40),
        ] {
            bytes[offset..offset + 4].copy_from_slice(&value.to_le_bytes());
        }
        let library_name = b"libshow_host.dll\0";
        bytes[0x290..0x290 + library_name.len()].copy_from_slice(library_name);
        let mut name_offset = 0x600;
        for (index, name) in symbols.iter().enumerate() {
            bytes[0x300 + index * 4..0x304 + index * 4].copy_from_slice(&0x1f00_u32.to_le_bytes());
            bytes[0x400 + index * 4..0x404 + index * 4]
                .copy_from_slice(&(name_offset as u32 + 0xe00).to_le_bytes());
            bytes[0x500 + index * 2..0x502 + index * 2]
                .copy_from_slice(&(index as u16).to_le_bytes());
            bytes[name_offset..name_offset + name.len()].copy_from_slice(name.as_bytes());
            name_offset += name.len() + 1;
        }
        bytes[0x1040..0x1040 + import.len()].copy_from_slice(import.as_bytes());
        bytes
    }

    fn prepared(directory: &Path) {
        fs::create_dir_all(directory).unwrap();
        fs::write(directory.join(DLL), pe(REQUIRED_SYMBOLS, "KERNEL32.dll")).unwrap();
        for name in LICENSES {
            let path = directory.join(name);
            fs::create_dir_all(path.parent().unwrap()).unwrap();
            fs::write(path, format!("fixture license for {name}\n")).unwrap();
        }
    }

    #[test]
    fn opt_in_stages_exact_dll_and_licenses_and_opt_out_removes_stale_files() {
        let tree = tempfile::tempdir().unwrap();
        let source = tree.path().join("准备 Show input & files");
        prepared(&source);
        let layout = Layout::new(&tree.path().join("native output"), false);
        fs::create_dir_all(&layout.vendor).unwrap();
        let config = configuration(tree.path(), Some(&source), "windows", "x86_64");
        stage(&config, &layout).unwrap();
        assert_eq!(
            fs::read(source.join(DLL)).unwrap(),
            fs::read(layout.vendor.join("show-host").join(DLL)).unwrap()
        );
        for name in LICENSES {
            assert_eq!(
                fs::read(source.join(name)).unwrap(),
                fs::read(
                    layout
                        .docs
                        .join("THIRD_PARTY_LICENSES/kirakara-show")
                        .join(name)
                )
                .unwrap()
            );
        }
        fs::write(layout.vendor.join("unrelated.dll"), b"keep").unwrap();
        stage(
            &configuration(tree.path(), None, "windows", "x86_64"),
            &layout,
        )
        .unwrap();
        assert!(!layout.vendor.join("show-host").join(DLL).exists());
        assert_eq!(
            fs::read(layout.vendor.join("unrelated.dll")).unwrap(),
            b"keep"
        );
        assert!(source.join(DLL).is_file());
    }

    #[test]
    fn invalid_inputs_never_replace_existing_output() {
        let tree = tempfile::tempdir().unwrap();
        let source = tree.path().join("prepared");
        prepared(&source);
        let layout = Layout::new(&tree.path().join("output"), false);
        fs::create_dir_all(layout.vendor.join("show-host")).unwrap();
        let output = layout.vendor.join("show-host").join(DLL);
        fs::write(&output, b"previous valid output").unwrap();
        let config = configuration(tree.path(), Some(&source), "windows", "x86_64");
        for (name, invalid) in [
            (DLL, Vec::new()),
            ("libshow_host.dll.LICENSES.txt", Vec::new()),
            (DLL, pe(&REQUIRED_SYMBOLS[1..], "KERNEL32.dll")),
            (DLL, pe(REQUIRED_SYMBOLS, "private-codec.dll")),
        ] {
            let path = source.join(name);
            let original = fs::read(&path).unwrap();
            fs::write(&path, invalid).unwrap();
            assert!(stage(&config, &layout).is_err());
            assert_eq!(fs::read(&output).unwrap(), b"previous valid output");
            fs::write(&path, original).unwrap();
        }
        fs::remove_file(source.join(DLL)).unwrap();
        assert!(stage(&config, &layout).is_err());
        assert_eq!(fs::read(&output).unwrap(), b"previous valid output");
    }

    #[test]
    fn rejects_overlapping_outputs_and_unsupported_platforms() {
        let tree = tempfile::tempdir().unwrap();
        let layout = Layout::new(tree.path(), false);
        let source = layout.vendor.join("show-host");
        prepared(&source);
        let config = configuration(tree.path(), Some(&source), "windows", "x86_64");
        assert!(
            stage(&config, &layout)
                .unwrap_err()
                .to_string()
                .contains("separate")
        );
        for (os, arch) in [
            ("linux", "x86_64"),
            ("macos", "x86_64"),
            ("windows", "arm64"),
        ] {
            assert!(
                stage(
                    &configuration(tree.path(), Some(&source), os, arch),
                    &layout
                )
                .unwrap_err()
                .to_string()
                .contains("only native Windows x64")
            );
        }
        assert!(source.join(DLL).is_file());
    }
}
